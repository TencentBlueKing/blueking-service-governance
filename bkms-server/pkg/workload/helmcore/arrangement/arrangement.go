// AppArranger arranges the application to enable various functionalities.
// This is often achieved by using special placeholders in the values.yaml file.
type AppArranger struct {
	appStore bkmsapp.ApplicationStore
}

// NewAppArranger creates a new WorkloadImageArranger with the given store.
func NewAppArranger(appStore bkmsapp.ApplicationStore) *AppArranger {
	return &AppArranger{
		appStore: appStore,
	}
}

// ArrgResult is a struct that contains the arrangement result of the application,
// it can be also used as the result of validation of the arrangement.
type ArrgResult struct {
	WorkloadImage ArrgResultItem
	IngressDomain ArrgResultItem
}

// ArrgResultItem is a single item for holding the result status for a specific arrangement type.
type ArrgResultItem struct {
	// Status is the status of the arrangement
	Status ValuesArrangeStatus
	// SkippedReason is the reason why the arrangement was skipped, only used when the status is "skipped."
	SkippedReason string
}

// ValidateFileContent validates the given file content based on the file format.
// For YAML format, it validates the values YAML placeholders.
// For TAF format, it returns success directly (TAF format does not require placeholder validation).
//
// - content: the file content
// - format: the file format (yaml or taf)
func (arrg *AppArranger) ValidateFileContent(
	ctx context.Context,
	app *bkmsapp.Application,
	content []byte,
	format appcfg.FileFormat,
) (ArrgResult, error) {
	switch format {
	case appcfg.FileFormatTAF:
		return validateTAFFile(content)
	case appcfg.FileFormatYAML:
		return validateYamlFile(content)
	default:
		return ArrgResult{}, errors.New("invalid file format")
	}
}

// validateYamlFile validates YAML format file content.
// yaml.Unmarshal only checks syntax; variable extraction uses render.ExtractVars
// directly on raw content so both validators share one parse result.
func validateYamlFile(content []byte) (ArrgResult, error) {
	var dummy map[string]any
	if err := yaml.Unmarshal(content, &dummy); err != nil {
		return ArrgResult{}, errors.Wrap(err, "parsing values.yaml")
	}

	vars, err := render.ExtractVars(string(content))
	if err != nil {
		return ArrgResult{}, errors.Wrap(err, "extract placeholder vars from values.yaml")
	}

	errWorkloadImage := validateValuesYamlWorkloadImage(vars)
	// FIXME: 目前该占位符没有实际作用，考虑去掉检查
	errIngressDomain := validateValuesYamlIngressDomain(vars)

	errToItem := func(err error) ArrgResultItem {
		if err != nil {
			return ArrgResultItem{Status: ArrgStatusSkipped, SkippedReason: err.Error()}
		}
		return ArrgResultItem{Status: ArrgStatusConfigured, SkippedReason: ""}
	}

	return ArrgResult{
		WorkloadImage: errToItem(errWorkloadImage),
		IngressDomain: errToItem(errIngressDomain),
	}, nil
}

// validateTAFFile validates TAF format file content.
// TAF format does not require placeholder validation, so it returns success directly.
func validateTAFFile(_ []byte) (ArrgResult, error) {
	return ArrgResult{
		WorkloadImage: ArrgResultItem{Status: ArrgStatusConfigured, SkippedReason: ""},
		IngressDomain: ArrgResultItem{Status: ArrgStatusConfigured, SkippedReason: ""},
	}, nil
}

// Validate the values data to know if it's valid for the workloadImage arrangement.
func validateValuesYamlWorkloadImage(vars render.VarsSet) error {
	bkms := vars[string(render.ContextBkms)]

	// 以下场景三选一均可通过校验
	// image = ${{ bkms.ARTIFACT_IMAGE }}
	// image = ${{ bkms.ARTIFACT_IMAGE_NAME }}:${{ bkms.ARTIFACT_IMAGE_TAG }}
	// image = ${{ bkms.ARTIFACT_IMAGE_REGISTRY }}/${{ bkms.ARTIFACT_IMAGE_REPOSITORY }}:${{ bkms.ARTIFACT_IMAGE_TAG }}
	_, ok := bkms[BkmsArtifactImage]
	if ok {
		return nil
	}
	_, nameOK := bkms[BkmsArtifactImageName]
	_, tagOK := bkms[BkmsArtifactImageTag]
	if nameOK && tagOK {
		return nil
	}
	_, regOK := bkms[BkmsArtifactImageRegistry]
	_, repoOK := bkms[BkmsArtifactImageRepository]
	if regOK && repoOK && tagOK {
		return nil
	}
	return errors.New("missing image placeholders in values.yaml")
}

// Validate the values data to know if it's valid for the ingressDomain arrangement
func validateValuesYamlIngressDomain(vars render.VarsSet) error {
	bkms := vars[string(render.ContextBkms)]
	if _, ok := bkms[BkmsNetworkingIngressDomain]; ok {
		return nil
	}
	return errors.New("missing ingress domain placeholder in values.yaml")
}
