// 以下常量是编排 values.yaml 时 bkms 命名空间下可用的占位符变量键，
// 即模板中 ${{ bkms.X }} 里的 X。这些变量在编排期（校验、渲染）使用，
// 由部署侧填充具体值后传入渲染器。按业务类别加前缀分组：
// ARTIFACT_（构件/镜像）、APP_（应用）、NETWORKING_（网络）。
const (
	// BkmsArtifactImage is the full image representation
	// e.g. "myapp:1.0.0" or "hub.bktencent.com/blueking/myapp:1.0.0"
	BkmsArtifactImage = "ARTIFACT_IMAGE"
	// BkmsArtifactImageName is image name only (maybe use default registry)
	// e.g. "myapp" or "hub.bktencent.com/blueking/myapp"
	BkmsArtifactImageName = "ARTIFACT_IMAGE_NAME"
	// BkmsArtifactImageTag is image tag only
	// e.g. "1.0.0" or "v20250701"
	BkmsArtifactImageTag = "ARTIFACT_IMAGE_TAG"
	// BkmsArtifactImageRegistry is image registry
	// e.g. "my-registry.com" or "hub.bktencent.com"
	BkmsArtifactImageRegistry = "ARTIFACT_IMAGE_REGISTRY"
	// BkmsArtifactImageRepository is image repository (cannot with registry)
	// e.g. "myapp" or "blueking/myapp"
	BkmsArtifactImageRepository = "ARTIFACT_IMAGE_REPOSITORY"
	// BkmsAppImagePullSecret is the image pull secret name
	// e.g. "my-registry-secret"
	BkmsAppImagePullSecret = "APP_IMAGE_PULL_SECRET" // #nosec G101
	// BkmsNetworkingIngressDomain is the domain generated by the platform and designed
	// for use by the application's Ingress resource, e.g., "app-foobar.example.com"
	BkmsNetworkingIngressDomain = "NETWORKING_INGRESS_DOMAIN"
)

// ArrgType is a type that represents the arrangement type of an application.
type ArrgType string

const (
	// ArrgTypeWorkloadImage "应用源镜像" 编排类型
	ArrgTypeWorkloadImage ArrgType = "workloadImage"
	// ArrgTypeIngressDomain "网络访问 Ingress 域名" 编排类型
	ArrgTypeIngressDomain ArrgType = "ingressDomain"
)

// ValuesArrangeStatus is Values arrangement is a kind of "application arrangement" that is
// performed by defining a custom values.yaml file.
// The arrangement might have different statuses depending on the application.
type ValuesArrangeStatus string

const (
	// ArrgStatusUninitialized indicates that arrange has not been started yet.
	ArrgStatusUninitialized ValuesArrangeStatus = "uninitialized"
	// ArrgStatusConfigured indicates that arrange has been completed.
	ArrgStatusConfigured ValuesArrangeStatus = "configured"
	// ArrgStatusSkipped indicates that arrange has been skipped.
	ArrgStatusSkipped ValuesArrangeStatus = "skipped"
)

// AppArrgStatus is An application's arrangement status, every struct value
// represents an application's arrangement status for a specific arrangement type.
type AppArrgStatus struct {
	// WorkspaceID is the id of the workspace.
	WorkspaceID string `bson:"workspaceID"`
	// AppName is the name of the application.
	AppName string `bson:"appName"`
	// ArrgType is the type of the arrangement.
	ArrgType ArrgType `bson:"arrgType"`
	// Status is the status of the arrangement.
	Status ValuesArrangeStatus `bson:"status"`

	// UpdatedAt is the time when the arrangement was last updated.
	UpdatedAt int64 `bson:"updatedAt"`
}

// PlaceholderVar 是编排 values.yaml 时的可用占位符。
