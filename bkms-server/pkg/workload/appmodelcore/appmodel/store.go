// CollectionName is the name of the MongoDB collection for storing app model data.
const CollectionName = "app_models"

// ErrAppModelNotFound is returned when a app model is not found in the store.
var ErrAppModelNotFound = errors.New("app model not found")

// ErrAppModelAlreadyExists is returned when creating an app model for an app that already has one.
var ErrAppModelAlreadyExists = errors.New("app model with the same appID already exists")

// ErrComponentNotFound is returned when a component is not found in the app model.
var ErrComponentNotFound = errors.New("component not found")

// ErrComponentNameExists is returned when a component name already exists in the app model.
var ErrComponentNameExists = errors.New("component name already exists")

// ErrEnvVarNotFound is returned when an env var is not found in the app model.
var ErrEnvVarNotFound = errors.New("env var not found")

// ErrEnvVarKeyExists is returned when an env var key already exists in the app model.
var ErrEnvVarKeyExists = errors.New("env var key already exists")

// ErrInvalidEnvVarKey is returned when an env var key does not satisfy the Pod env var naming rules.
var ErrInvalidEnvVarKey = errors.New("invalid env var key")

// ErrEnvVarSensitivityImmutable is returned when attempting to change a sensitive env var to non-sensitive.
// Sensitive env vars can only be deleted and recreated, not downgraded.
var ErrEnvVarSensitivityImmutable = errors.New("sensitive env var cannot be changed to non-sensitive")

// ComponentUpdateData 定义了更新 Component 时允许修改的数据
type ComponentUpdateData struct {
	// Name 组件名称
	Name *string
	// Version 组件版本
	Version *string
	// Properties 组件属性
	Properties map[string]any
}

// AppModelStore 应用模型的 GenericStore
type AppModelStore = store.GenericStore[AppModel]

// AppModelMeta 应用模型的存储元信息：
//   - BeforeSave 补齐组件名称并做结构体校验
//   - Encode 加密敏感的应用自定义环境变量，Decode 解密并规范化组件属性，
//     因此所有读取方（部署、序列化等）拿到的都是明文
//
// 组件增删会影响 ComponentDef 的引用计数，须通过 AddComponent / RemoveComponent / DeleteAppModel 完成；
// 环境变量的增删改须通过 AddAppDefinedEnvVar 等函数完成，它们绕过 Encode，自行加密。
//
// 索引（由 golang-migrate 维护）：
// - 唯一：appID
var AppModelMeta = store.Meta[AppModel]{
	Collection: CollectionName,
	NotFound:   ErrAppModelNotFound,
	Duplicate:  ErrAppModelAlreadyExists,
	BeforeSave: []func(*AppModel) error{validateAppModel},
	Encode:     []func(*AppModel) error{encryptAppModelEnvVars},
	Decode:     []func(*AppModel) error{decodeAppModel},
}

// ByApp 按应用 ID 匹配应用模型
func ByApp(appID string) store.Opt { return store.Where("appID", appID) }

// CreateAppModel creates a new app model, the created and updated time of env vars are set to now.
// Returns ErrAppModelAlreadyExists if the app already has an app model.
func CreateAppModel(ctx context.Context, db *mongo.Database, appModel *AppModel) error {
	now := time.Now()
	for i := range appModel.Workload.EnvVars {
		appModel.Workload.EnvVars[i].CreatedAt = now
		appModel.Workload.EnvVars[i].UpdatedAt = now
	}
	if err := store.Of(db, AppModelMeta).Create(ctx, appModel); err != nil {
		return errors.Wrapf(err, "create app model of app %s", appModel.AppID)
	}
	return nil
}

// UpdateAppModel replaces the app model of appModel.AppID as a whole,
// if appModel.Components.Name is empty, it will be generated by the system.
// Returns ErrAppModelNotFound if the app model is not found.
func UpdateAppModel(ctx context.Context, db *mongo.Database, appModel *AppModel) error {
	if err := store.Of(db, AppModelMeta).Replace(ctx, appModel, ByApp(appModel.AppID)); err != nil {
		return errors.Wrapf(err, "update app model of app %s", appModel.AppID)
	}
	return nil
}

// DeleteAppModel deletes an app model by appID, and decreases the reference count of its components' defs.
// Returns ErrAppModelNotFound if the app model is not found.
func DeleteAppModel(ctx context.Context, db *mongo.Database, appID string) error {
	appModel, err := store.Of(db, AppModelMeta).GetAndDelete(ctx, ByApp(appID))
	if err != nil {
		return errors.Wrapf(err, "delete app model of app %s", appID)
	}
	return adjustInstanceCounts(ctx, db, appModel.Components, -1)
}

// AddComponent adds a component to an app model atomically using $push,
// and increases the reference count of the component def.
// Returns ErrAppModelNotFound if app model not found, ErrComponentNameExists if component name already exists.
func AddComponent(ctx context.Context, db *mongo.Database, appID string, comp *component.Component) error {
	// Ensure the component has a name
	comp.EnsureName()
	if err := validate.Struct(comp); err != nil {
		return errors.Wrap(formatValidationError(err), "component validation failed")
	}

	// Use filter to check app model exists and component name does not exist
	models := store.Of(db, AppModelMeta)
	_, err := models.Modify(ctx, bson.M{"$push": bson.M{"components": comp}},
		ByApp(appID),
		store.Where("components", bson.M{"$not": bson.M{"$elemMatch": bson.M{"name": comp.Name}}}),
	)
	if errors.Is(err, ErrAppModelNotFound) {
		err = classifyMiss(ctx, models, appID, ErrComponentNameExists)
	}
	if err != nil {
		return errors.Wrapf(err, "add component %s to app model of app %s", comp.Name, appID)
	}
	return adjustInstanceCounts(ctx, db, []*component.Component{comp}, 1)
}

// UpdateComponent updates a component in an app model atomically using arrayFilters.
// Returns ErrAppModelNotFound if app model not found, ErrComponentNotFound if component not found,
// ErrComponentNameExists if new name conflicts with existing component.
func UpdateComponent(
	ctx context.Context,
	db *mongo.Database,
	appID, compName string,
	updateData *ComponentUpdateData,
) error {
	if updateData == nil {
		return nil
	}

	conds := []store.Opt{ByApp(appID), store.Where("components.name", compName)}
	updateSet := bson.M{}

	// Handle name update with uniqueness check
	renamed := updateData.Name != nil && *updateData.Name != "" && *updateData.Name != compName
	if renamed {
		// Check that no other component has the new name
		conds = append(conds, store.Where("$nor", []bson.M{
			{"components": bson.M{"$elemMatch": bson.M{"name": *updateData.Name}}},
		}))
		updateSet["components.$[elem].name"] = *updateData.Name
	}
	if updateData.Version != nil {
		updateSet["components.$[elem].version"] = *updateData.Version
	}
	if updateData.Properties != nil {
		updateSet["components.$[elem].properties"] = updateData.Properties
	}
	if len(updateSet) == 0 {
		return nil
	}

	models := store.Of(db, AppModelMeta)
	_, err := models.Modify(ctx, bson.M{"$set": updateSet},
		append(conds, store.ArrayFilters(bson.M{"elem.name": compName}))...)
	if errors.Is(err, ErrAppModelNotFound) {
		err = classifyComponentMiss(ctx, models, appID, compName, renamed)
	}
	if err != nil {
		return errors.Wrapf(err, "update component %s in app model of app %s", compName, appID)
	}
	return nil
}

// RemoveComponent removes a component from an app model atomically using $pull,
// and decreases the reference count of the component def.
// Returns ErrAppModelNotFound if app model not found, ErrComponentNotFound if component not found.
func RemoveComponent(ctx context.Context, db *mongo.Database, appID, compName string) error {
	// 先查出被删除的组件，以便按类型扣减引用计数
	models := store.Of(db, AppModelMeta)
	appModel, err := models.Get(ctx, ByApp(appID))
	if err != nil {
		return errors.Wrapf(err, "get app model of app %s", appID)
	}
	removed, found := lo.Find(appModel.Components, func(c *component.Component) bool { return c.Name == compName })
	if !found {
		return errors.Wrapf(ErrComponentNotFound, "component %s of app %s", compName, appID)
	}

	// 过滤条件要求组件仍存在：查询与删除之间组件被并发删除时不会匹配，避免重复扣减引用计数。
	// 不依赖 Modified == 0 判断：模型一旦带上 updatedAt，刷新时间戳也会计入 Modified
	_, err = models.Modify(ctx, bson.M{"$pull": bson.M{"components": bson.M{"name": compName}}},
		ByApp(appID), store.Where("components.name", compName))
	if errors.Is(err, ErrAppModelNotFound) {
		err = classifyMiss(ctx, models, appID, ErrComponentNotFound)
	}
	if err != nil {
		return errors.Wrapf(err, "remove component %s from app model of app %s", compName, appID)
	}
	return adjustInstanceCounts(ctx, db, []*component.Component{removed}, -1)
}

// AddAppDefinedEnvVar appends one app-defined env var atomically using $push.
// Missing CreatedAt and UpdatedAt values are initialized before persistence.
// Returns ErrAppModelNotFound if app model not found, ErrEnvVarKeyExists if key already exists.
func AddAppDefinedEnvVar(ctx context.Context, db *mongo.Database, appID string, envVar Variable) error {
	if envVar.CreatedAt.IsZero() {
		envVar.CreatedAt = time.Now()
	}
	if envVar.UpdatedAt.IsZero() {
		envVar.UpdatedAt = envVar.CreatedAt
	}

	// Modify 不经过 Encode，敏感变量须在这里加密
	stored := envVar
	if envVar.IsSensitive {
		encrypted, err := crypto.AESEncrypt(config.G.Encrypt.Secret, envVar.Value)
		if err != nil {
			return errors.Wrapf(err, "encrypt env var %s", envVar.Key)
		}
		stored.Value = encrypted
	}

	models := store.Of(db, AppModelMeta)
	_, err := models.Modify(ctx, bson.M{"$push": bson.M{"workload.envVars": stored}},
		ByApp(appID),
		store.Where("workload.envVars", bson.M{"$not": bson.M{"$elemMatch": bson.M{"key": envVar.Key}}}),
	)
	if errors.Is(err, ErrAppModelNotFound) {
		err = classifyMiss(ctx, models, appID, ErrEnvVarKeyExists)
	}
	if err != nil {
		return errors.Wrapf(err, "add env var %s to app model of app %s", envVar.Key, appID)
	}
	return nil
}

// UpdateAppDefinedEnvVar updates one app-defined env var atomically by key.
// Missing UpdatedAt is initialized before persistence. CreatedAt is immutable.
// Returns ErrAppModelNotFound if app model not found, ErrEnvVarNotFound if env var not found,
// ErrEnvVarKeyExists if renamed key conflicts with an existing one.
func UpdateAppDefinedEnvVar(ctx context.Context, db *mongo.Database, appID, key string, updated Variable) error {
	if updated.UpdatedAt.IsZero() {
		updated.UpdatedAt = time.Now()
	}

	conds := []store.Opt{ByApp(appID), store.Where("workload.envVars.key", key)}
	if updated.Key != key {
		conds = append(conds, store.Where("$nor", []bson.M{
			{"workload.envVars": bson.M{"$elemMatch": bson.M{"key": updated.Key}}},
		}))
	}

	value := updated.Value
	if updated.IsSensitive {
		encrypted, err := crypto.AESEncrypt(config.G.Encrypt.Secret, updated.Value)
		if err != nil {
			return errors.Wrapf(err, "encrypt env var %s", updated.Key)
		}
		value = encrypted
	}

	// CreatedAt is immutable and intentionally omitted from $set.
	update := bson.M{
		"$set": bson.M{
			"workload.envVars.$[elem].key":         updated.Key,
			"workload.envVars.$[elem].value":       value,
			"workload.envVars.$[elem].description": updated.Description,
			"workload.envVars.$[elem].isSensitive": updated.IsSensitive,
			"workload.envVars.$[elem].updatedAt":   updated.UpdatedAt,
		},
	}
	models := store.Of(db, AppModelMeta)
	_, err := models.Modify(ctx, update, append(conds, store.ArrayFilters(bson.M{"elem.key": key}))...)
	if errors.Is(err, ErrAppModelNotFound) {
		err = classifyEnvVarMiss(ctx, models, appID, key)
	}
	if err != nil {
		return errors.Wrapf(err, "update env var %s in app model of app %s", key, appID)
	}
	return nil
}

// RemoveAppDefinedEnvVar removes one app-defined env var atomically by key.
// Returns ErrAppModelNotFound if app model not found, ErrEnvVarNotFound if env var not found.
func RemoveAppDefinedEnvVar(ctx context.Context, db *mongo.Database, appID, key string) error {
	models := store.Of(db, AppModelMeta)
	_, err := models.Modify(ctx, bson.M{"$pull": bson.M{"workload.envVars": bson.M{"key": key}}},
		ByApp(appID), store.Where("workload.envVars.key", key))
	if errors.Is(err, ErrAppModelNotFound) {
		err = classifyMiss(ctx, models, appID, ErrEnvVarNotFound)
	}
	if err != nil {
		return errors.Wrapf(err, "remove env var %s from app model of app %s", key, appID)
	}
	return nil
}

// ListAppDefinedEnvVars lists app-defined env vars stored in workload.envVars.
// Returns ErrAppModelNotFound if the app model is not found.
func ListAppDefinedEnvVars(ctx context.Context, db *mongo.Database, appID string) ([]Variable, error) {
	appModel, err := store.Of(db, AppModelMeta).Get(ctx, ByApp(appID))
	if err != nil {
		return nil, errors.Wrapf(err, "get app model of app %s", appID)
	}
	return appModel.Workload.EnvVars, nil
}

// classifyMiss 在带元素条件的写操作未命中后，区分是应用模型不存在，还是元素条件不满足（返回 elemErr）
func classifyMiss(ctx context.Context, models *AppModelStore, appID string, elemErr error) error {
	exists, err := models.Exists(ctx, ByApp(appID))
	if err != nil {
		return errors.Wrap(err, "check app model exists")
	}
	if !exists {
		return ErrAppModelNotFound
	}
	return elemErr
}

// classifyComponentMiss 组件更新未命中时，区分模型不存在、组件不存在与新名称冲突
func classifyComponentMiss(
	ctx context.Context, models *AppModelStore, appID, compName string, renamed bool,
) error {
	if !renamed {
		return classifyMiss(ctx, models, appID, ErrComponentNotFound)
	}
	return classifyElemMiss(ctx, models, appID, store.Where("components.name", compName),
		ErrComponentNotFound, ErrComponentNameExists)
}

// classifyEnvVarMiss 环境变量更新未命中时，区分模型不存在、变量不存在与新 key 冲突
func classifyEnvVarMiss(ctx context.Context, models *AppModelStore, appID, key string) error {
	return classifyElemMiss(ctx, models, appID, store.Where("workload.envVars.key", key),
		ErrEnvVarNotFound, ErrEnvVarKeyExists)
}

// classifyElemMiss 应用模型存在时，元素（elemCond）不存在返回 notFoundErr，否则视为与其它元素冲突，返回 conflictErr
func classifyElemMiss(
	ctx context.Context, models *AppModelStore, appID string, elemCond store.Opt, notFoundErr, conflictErr error,
) error {
	if err := classifyMiss(ctx, models, appID, nil); err != nil {
		return err
	}
	elemExists, err := models.Exists(ctx, ByApp(appID), elemCond)
	if err != nil {
		return errors.Wrap(err, "check app model element exists")
	}
	if !elemExists {
		return notFoundErr
	}
	return conflictErr
}

// adjustInstanceCounts 按组件类型汇总后调整 ComponentDef.AppCompInstanceCount，sign 为 1 增加、-1 减少。
// 引用空间组件的应用组件不是该组件定义的实例，不计入
func adjustInstanceCounts(ctx context.Context, db *mongo.Database, comps []*component.Component, sign int) error {
	typeCounts := map[string]int{}
	for _, comp := range comps {
		if comp.Type != "" && comp.RefWorkspaceCompName == "" {
			typeCounts[comp.Type]++
		}
	}
	defs := store.Of(db, component.ComponentDefMeta)
	for compType, count := range typeCounts {
		if err := component.UpdateInstanceCount(
			ctx, defs, compType, component.FieldAppCompInstance, sign*count,
		); err != nil {
			return errors.Wrapf(err, "adjust appCompInstanceCount of %s by %d", compType, sign*count)
		}
	}
	return nil
}

// validateAppModel 补齐组件名称，并校验结构体以确保必填字段存在
func validateAppModel(appModel *AppModel) error {
	appModel.EnsureComponentsName()
	if err := validate.Struct(appModel); err != nil {
		return errors.Wrap(formatValidationError(err), "app model validation failed")
	}
	return nil
}

func encryptAppModelEnvVars(appModel *AppModel) error {
	return encryptSensitiveEnvVars(appModel.Workload.EnvVars)
}

func decodeAppModel(appModel *AppModel) error {
	appModel.NormalizeComponents()
	// Decrypt sensitive app-defined env vars so all callers (e.g. deployment,
	// serializers) see the plaintext value.
	decryptSensitiveEnvVars(appModel.Workload.EnvVars)
	return nil
}

// encryptSensitiveEnvVars encrypts the values of sensitive app-defined env vars in
// place. Non-sensitive vars are left as plaintext on purpose so the bulk of existing
// data does not need to be migrated.
func encryptSensitiveEnvVars(vars []Variable) error {
	for i := range vars {
		if !vars[i].IsSensitive {
			continue
		}
		encrypted, err := crypto.AESEncrypt(config.G.Encrypt.Secret, vars[i].Value)
		if err != nil {
			return errors.Wrapf(err, "encrypt env var %s", vars[i].Key)
		}
		vars[i].Value = encrypted
	}
	return nil
}

// decryptSensitiveEnvVars decrypts the values of sensitive app-defined env vars in
// place. For backward compatibility with sensitive vars that were previously stored
// as plaintext, a decryption failure leaves the original value unchanged, so no data
// migration is required.
func decryptSensitiveEnvVars(vars []Variable) {
	for i := range vars {
		if !vars[i].IsSensitive {
			continue
		}
		decrypted, err := crypto.AESDecrypt(config.G.Encrypt.Secret, vars[i].Value)
		if err != nil {
			continue
		}
		vars[i].Value = decrypted
	}
}
