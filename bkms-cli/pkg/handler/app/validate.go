// Package app 提供应用创建相关的处理逻辑
package app

import (
	"fmt"
	"reflect"
	"regexp"
	"strings"

	"github.com/go-playground/validator/v10"
	"github.com/pkg/errors"

	"github.com/TencentBlueKing/blueking-service-governance/bkms-cli/pkg/constant"
)

// appValidator 全局 validator 实例
var appValidator *validator.Validate

// nameRegexp 应用名称校验正则：小写字母开头，可含小写字母/数字/中划线，不以中划线结尾，1~63字符
var nameRegexp = regexp.MustCompile(`^[a-z](?:[a-z0-9-]*[a-z0-9])?$`)

func init() {
	appValidator = validator.New(validator.WithRequiredStructEnabled())

	appValidator.RegisterTagNameFunc(func(fld reflect.StructField) string {
		name := strings.SplitN(fld.Tag.Get("yaml"), ",", 2)[0]
		if name == "-" {
			return ""
		}
		if name == "" {
			return fld.Name
		}
		return name
	})

	// 注册自定义 tag 校验器
	_ = appValidator.RegisterValidation("app_name", validateAppName)
}

// Validate 校验 AppCreateSpec 的合法性
// CLI 端仅做不为空校验和格式校验（名称正则、枚举值），提供快速反馈；
// 完整的业务规则校验（如框架与语言组合）以后端为准。
func (s *AppCreateSpec) Validate() error {
	// 对所有字符串字段去除前后空格
	s.TrimSpace()
	if s.ID != "" {
		return errors.New("'id' is not supported: app ID is generated by the server as '<name>-<suffix>', " +
			"please remove the 'id' field")
	}
	if err := appValidator.Struct(s); err != nil {
		return formatValidationError(err)
	}
	return s.validateStack()
}

// validateStack 校验应用类型与框架的组合，并把旧的 type: trpc/taf 写法归一化为 framework + language
func (s *AppCreateSpec) validateStack() error {
	switch s.Type {
	case constant.AppTypeHelm, constant.AppTypeAgones:
		if s.Framework != "" || s.Language != "" {
			return errors.Errorf("'framework' / 'language' are not supported for %s applications", s.Type)
		}
		return nil
	case constant.AppTypeTrpc, constant.AppTypeTaf:
		if s.Framework != "" && s.Framework != s.Type {
			return errors.Errorf(
				"'type: %s' conflicts with 'framework: %s', please only use 'framework'",
				s.Type,
				s.Framework,
			)
		}
		return s.normalizeLegacyStack()
	case constant.AppTypeBKMSApp, "":
		// 新写法：由 framework 决定技术栈
	default:
		return errors.Errorf("unsupported app type: %s", s.Type)
	}

	if s.Framework == "" {
		return errors.New("either 'framework: trpc|taf|blank' or 'type: helm|agones' is required")
	}
	if s.Language == "" {
		return errors.Errorf("'language' is required when 'framework' is %s", s.Framework)
	}
	return s.validateFrameworkConfigFile()
}

// normalizeLegacyStack 把旧的 type: trpc/taf 写法转换为新字段，保持已有脚本可用
func (s *AppCreateSpec) normalizeLegacyStack() error {
	if s.Framework == "" {
		s.Framework = s.Type
	}
	spec := s.AppModelSpec
	if s.Language == "" && spec != nil {
		switch {
		case spec.TrpcSpec != nil:
			s.Language = spec.TrpcSpec.Language
		case spec.TafSpec != nil:
			// TAF 只支持 C++
			s.Language = "cpp"
		}
	}
	if s.Language == "" {
		s.Language = "cpp"
		if s.Framework == constant.FrameworkTrpc {
			return errors.New("'language' is required for trpc applications")
		}
	}
	if s.FrameworkConfigFile == nil && spec != nil {
		switch {
		case spec.TrpcSpec != nil:
			s.FrameworkConfigFile = &FrameworkConfigFileSpec{
				Name:     spec.TrpcSpec.FileName,
				MountDir: spec.TrpcSpec.FilePath,
				Content:  spec.TrpcSpec.FileContent,
			}
		case spec.TafSpec != nil:
			s.FrameworkConfigFile = &FrameworkConfigFileSpec{
				Name:     spec.TafSpec.FileName,
				MountDir: spec.TafSpec.FilePath,
				Content:  spec.TafSpec.FileContent,
			}
		}
	}
	if s.FrameworkConfigFile == nil {
		return errors.Errorf("'appModelSpec.%sSpec' or 'frameworkConfigFile' is required for %s applications",
			s.Framework, s.Framework)
	}
	return nil
}

// validateFrameworkConfigFile 校验框架配置文件：trpc/taf 必填，blank 不能传
func (s *AppCreateSpec) validateFrameworkConfigFile() error {
	if s.Framework == constant.FrameworkBlank {
		if s.FrameworkConfigFile != nil {
			return errors.New("'frameworkConfigFile' is not supported for framework 'blank'")
		}
		return nil
	}
	if s.FrameworkConfigFile == nil {
		return errors.Errorf("'frameworkConfigFile' is required for framework %s", s.Framework)
	}
	return nil
}

// validateAppName 自定义 app_name tag 校验器
func validateAppName(fl validator.FieldLevel) bool {
	name := fl.Field().String()
	if len(name) < 1 || len(name) > 63 {
		return false
	}
	return nameRegexp.MatchString(name)
}

// formatValidationError 将 validator 错误转换为用户友好的错误信息，只返回第一个错误保持 CLI 输出简洁
func formatValidationError(err error) error {
	validationErrors, ok := err.(validator.ValidationErrors)
	if !ok {
		return err
	}
	return errors.New(buildFieldErrorMessage(validationErrors[0]))
}

// buildFieldErrorMessage 根据 FieldError 构建用户友好的错误信息
func buildFieldErrorMessage(fe validator.FieldError) string {
	namespace := fe.Namespace()
	field := namespace
	if idx := strings.Index(namespace, "."); idx != -1 {
		field = namespace[idx+1:]
	}

	switch fe.Tag() {
	case "required":
		return fmt.Sprintf("'%s' is required", field)
	case "oneof":
		return fmt.Sprintf("'%s' is invalid: must be one of [%s], got %q",
			field, strings.ReplaceAll(fe.Param(), " ", ", "), fe.Value())
	case "app_name":
		return fmt.Sprintf("'%s' is invalid: must start with a lowercase letter, "+
			"contain only lowercase letters, digits, and hyphens, not end with a hyphen, and be 1~63 characters", field)
	default:
		return fmt.Sprintf("'%s' failed validation on '%s' tag", field, fe.Tag())
	}
}
